import { AnchorProvider, Program, type Idl } from "@coral-xyz/anchor";
import {
	ASSOCIATED_TOKEN_PROGRAM_ID,
	getAssociatedTokenAddressSync,
	TOKEN_PROGRAM_ID,
} from "@solana/spl-token";
import type { Adapter } from "@solana/wallet-adapter-base";
import {
	PublicKey,
	type Connection,
	type Transaction,
	type VersionedTransaction,
} from "@solana/web3.js";
import idlJson from "@/lib/idl/man_faucet.json";
import type { ManFaucet } from "@/lib/idl/man_faucet";

/** Devnet deployment of the man_faucet program. */
export const PROGRAM_ID = new PublicKey(
	"222rpnLzA6VLmZxniTePoqasCYz72aYjBZLhVtYiwjkR",
);

/** IDL generated by `anchor build` in the program repository. */
export const MAN_FAUCET_IDL = idlJson as unknown as Idl;

export { ASSOCIATED_TOKEN_PROGRAM_ID, TOKEN_PROGRAM_ID };

/*
 * Seeds match `programs/man-faucet/src/constants.rs`:
 *   CONFIG_SEED = b"config"
 *   MINT_SEED   = b"mint"
 *   CLAIM_SEED  = b"claim"
 */
const CONFIG_SEED = new TextEncoder().encode("config");
const MINT_SEED = new TextEncoder().encode("mint");
const CLAIM_SEED = new TextEncoder().encode("claim");

/** Config PDA: seeds `["config"]`. */
export function getConfigAddress(): PublicKey {
	return PublicKey.findProgramAddressSync([CONFIG_SEED], PROGRAM_ID)[0];
}

/** MAN mint PDA: seeds `["mint"]`. */
export function getMintAddress(): PublicKey {
	return PublicKey.findProgramAddressSync([MINT_SEED], PROGRAM_ID)[0];
}

/** Per-wallet claim PDA: seeds `["claim", user]`. */
export function getUserClaimAddress(user: PublicKey): PublicKey {
	return PublicKey.findProgramAddressSync(
		[CLAIM_SEED, user.toBytes()],
		PROGRAM_ID,
	)[0];
}

/** The wallet's associated token account for the MAN mint. */
export function getUserAtaAddress(user: PublicKey): PublicKey {
	return getAssociatedTokenAddressSync(getMintAddress(), user);
}

/**
 * Anchor client for the faucet program.
 *
 * Transactions are built with `.transaction()` and sent through the wallet
 * adapter, so the provider's send helpers are never used.
 */
export function getProgram(
	connection: Connection,
	wallet: Adapter,
): Program<ManFaucet> {
	const publicKey = wallet.publicKey;

	if (!publicKey) {
		throw new Error("Connect a wallet before creating the program client.");
	}

	// Signer methods live on signer-capable adapters, not on the base Adapter
	// type. The claim flow sends through the adapter directly, so these are only
	// here to satisfy AnchorProvider's wallet shape.
	const signer = wallet as Adapter & {
		signTransaction?: <T extends Transaction | VersionedTransaction>(
			tx: T,
		) => Promise<T>;
		signAllTransactions?: <T extends Transaction | VersionedTransaction>(
			txs: T[],
		) => Promise<T[]>;
	};

	const provider = new AnchorProvider(
		connection,
		{
			publicKey,
			signTransaction: <T extends Transaction | VersionedTransaction>(tx: T) =>
				signer.signTransaction
					? signer.signTransaction(tx)
					: Promise.reject(
							new Error("This wallet cannot sign transactions."),
						),
			signAllTransactions: <T extends Transaction | VersionedTransaction>(
				txs: T[],
			) =>
				signer.signAllTransactions
					? signer.signAllTransactions(txs)
					: Promise.reject(
							new Error("This wallet cannot sign transactions."),
						),
		},
		{ commitment: "confirmed" },
	);

	return new Program<ManFaucet>(MAN_FAUCET_IDL, provider);
}
